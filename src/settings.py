import os
import sys
from pathlib import Path

# ===========================================================================
# CROSS-PLATFORM: Risoluzione percorsi (PyInstaller compatibile)
# ===========================================================================
def resource_path(relative_path: str) -> str:
    """Restituisce il percorso assoluto della risorsa, compatibile con PyInstaller."""
    if getattr(sys, 'frozen', False):
        base = sys._MEIPASS
    else:
        # Assumiamo che settings.py sia in src/ e il root sia un livello sopra
        base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, relative_path)

